begin
 assert to_regprocedure('public.request_friendship(text,uuid,uuid)') is not null,'social API missing';
 insert into auth.users(id) values(a),(b),(c); insert into private.beta_testers(user_id) values(a),(b),(c);
 perform set_config('request.jwt.claim.sub',a::text,true); set local role authenticated;
 r:=public.ensure_profile('Ana'); a_code:=r->'data'->>'public_code'; ac:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.ensure_profile('Bia'); b_code:=r->'data'->>'public_code'; bc:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 perform set_config('request.jwt.claim.sub',c::text,true);
 r:=public.ensure_profile('Carol'); c_code:=r->'data'->>'public_code'; cc:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.request_friendship(b_code,ac,gen_random_uuid()); request_:=(r->'data'->>'friend_request_id')::uuid;
 assert r->'data'->>'status'='pending' and request_ is not null,'friend request not pending';
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.request_friendship(a_code,bc,gen_random_uuid());
 assert r->'data'->>'status'='received_request','crossed request accepted automatically';
 r:=public.list_friends(null,20); assert jsonb_array_length(r->'data'->'friends')=0,'friendship created without acceptance';
 perform set_config('request.jwt.claim.sub',c::text,true);
 r:=public.answer_friend_request(request_,'accept',cc,gen_random_uuid());
 assert r->>'code'='NOT_FOUND_OR_UNAVAILABLE','outsider accepted friendship';
 r:=public.list_friend_requests('incoming',null,20);
 assert jsonb_array_length(r->'data'->'requests')=0,'unrelated request leaked';
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.answer_friend_request(request_,'accept',bc,gen_random_uuid());
 assert r->'data'->>'status'='accepted','accept failed';
 r:=public.list_friends(null,20);
 assert jsonb_array_length(r->'data'->'friends')=1 and r->'data'->'friends'->0->>'user_id'=a::text,'bilateral friendship missing';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.list_friends(null,20); assert jsonb_array_length(r->'data'->'friends')=1,'sender friendship missing';
 r:=public.create_room('Convite',false,ac,gen_random_uuid()); room_:=(r->'data'->>'room_id')::uuid; member_:=(r->'data'->>'membership_id')::uuid;
 r:=public.invite_friend(b,room_,member_,1,ac,gen_random_uuid()); invite_:=(r->'data'->>'invite_id')::uuid;
 assert invite_ is not null,'friend invitation missing';
 r:=public.remove_friend(b,ac,gen_random_uuid()); assert r->'data'->>'status'='removed','friend removal failed';
 r:=public.list_friends(null,20); assert jsonb_array_length(r->'data'->'friends')=0,'friend removal not bilateral';
