 assert (select count(*)=1 from private.notification_outbox where kind='invite' and resource_id=invite_),'duplicate invitation outbox';
 assert not exists(select 1 from private.notification_outbox o join private.friendship_requests f on f.id=o.resource_id
  where o.kind='friendship' and f.status<>'pending' and o.status in ('pending','leased')),'resolved request left active notification';
end
