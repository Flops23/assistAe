 r:=public.join_room(jsonb_build_object('invite_id',invite_),cc,gen_random_uuid());
 assert r->>'code'='NOT_FOUND_OR_UNAVAILABLE','outsider consumed invitation';
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.list_invites(null,20);
 assert jsonb_array_length(r->'data'->'invites')=1 and r->'data'->'invites'->0->>'id'=invite_::text,'removal invalidated existing invite';
 assert not(r->'data'->'invites'->0 ? 'code') and not(r->'data'->'invites'->0 ? 'source_url'),'invitation leaked room secrets';
 r:=public.join_room(jsonb_build_object('invite_id',invite_),bc,gen_random_uuid()); assert r->>'code' is null,'invite failed after friendship removal';
 r:=public.list_friends(null,20); assert jsonb_array_length(r->'data'->'friends')=0,'recipient retained removed friendship';
