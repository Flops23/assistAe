 r:=public.request_friendship(c_code,ac,gen_random_uuid()); request_:=(r->'data'->>'friend_request_id')::uuid;
 perform set_config('request.jwt.claim.sub',c::text,true);
 r:=public.cancel_friend_request(request_,cc,gen_random_uuid()); assert r->>'code'='NOT_FOUND_OR_UNAVAILABLE','recipient cancelled sender request';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.cancel_friend_request(request_,ac,gen_random_uuid()); assert r->'data'->>'status'='cancelled','sender cancellation failed';
 perform set_config('request.jwt.claim.sub',c::text,true);
 r:=public.request_friendship(a_code,cc,gen_random_uuid()); request_:=(r->'data'->>'friend_request_id')::uuid;
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.answer_friend_request(request_,'reject',ac,gen_random_uuid()); assert r->'data'->>'status'='rejected','rejection failed';
