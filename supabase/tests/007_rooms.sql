begin;
do $test$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid(); ctx uuid;
 r jsonb; room_ uuid; membership_ uuid; bm uuid; code_ text; req uuid:=gen_random_uuid(); old_deadline timestamptz; rev_before bigint;
begin
 assert to_regprocedure('public.create_room(text,boolean,uuid,uuid)') is not null, 'room API missing';
 insert into auth.users(id) values(a),(b),(outsider);
 insert into private.beta_testers(user_id) values(a),(b),(outsider);
 perform set_config('request.jwt.claim.sub',a::text,true);
 set local role authenticated;
 perform public.ensure_profile('Ana');
 ctx:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.create_room('Sala A',true,ctx,req);
 room_:=(r->'data'->>'room_id')::uuid;
 membership_:=(r->'data'->>'membership_id')::uuid;
 assert room_ is not null and membership_ is not null,'create did not admit admin';
 assert r->'data'->>'generation'='1','initial generation';
 r:=public.create_room('Sala A',true,ctx,req);
 assert r->>'outcome'='already_applied','create retry duplicated';
 r:=public.create_room('Sala B',true,ctx,gen_random_uuid());
 assert r->>'code'='ALREADY_IN_ROOM','one-room rule bypassed';
 r:=public.get_room_code(room_,membership_,1);
 code_:=r->'data'->>'code';
 assert length(code_)=12,'room code not issued';
 r:=public.get_room_snapshot(room_,membership_,1);
 assert r->'data'->'playback'->>'status'='empty','room started playback without media';
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.ensure_profile('Bia');
 ctx:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.join_room(jsonb_build_object('code',code_),ctx,gen_random_uuid());
 bm:=(r->'data'->>'membership_id')::uuid;
 assert bm is not null and r->'data'->>'room_id'=room_::text,'code join failed';
 r:=public.get_room_snapshot(room_,bm,1);
 assert jsonb_array_length(r->'data'->'participants')=2,'participant snapshot';
 r:=public.close_room(room_,bm,1,1,ctx,gen_random_uuid());
 assert r->>'code'='FORBIDDEN','ordinary participant closed room';
 perform set_config('request.jwt.claim.sub',outsider::text,true);
 perform public.ensure_profile('Carol');
 r:=public.get_room_snapshot(room_,bm,1);
 assert r->>'code'='NOT_FOUND_OR_UNAVAILABLE','outsider read room';
 reset role;
 select grace_deadline into old_deadline from private.connections where membership_id=bm;
 perform set_config('request.jwt.claim.sub',b::text,true);
 set local role authenticated;
 r:=public.heartbeat(room_,bm,1,1);
 assert r->>'code' is null,'heartbeat failed';
 reset role;
 select grace_deadline into old_deadline from private.connections where membership_id=bm;
 set local role authenticated;
 r:=public.heartbeat(room_,bm,1,1);
 reset role;
 assert (select grace_deadline=old_deadline from private.connections where membership_id=bm),'duplicate heartbeat extended lease';
 update private.connections set last_seen_at=statement_timestamp()-interval '30 seconds',suspect_at=statement_timestamp()-interval '5 seconds',
  grace_deadline=statement_timestamp()+interval '55 seconds' where membership_id=bm;
 update private.room_counters set last_message_seq=7 where room_id=room_;
 set local role authenticated;
 r:=public.get_room_snapshot(room_,bm,1);
 assert r->>'code'='RECONNECT_REQUIRED','grace read snapshot';
 ctx:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 req:=gen_random_uuid();
 r:=public.reconnect_room(room_,bm,1,ctx,req);
 assert r->'data'->>'generation'='2','reconnect did not advance generation';
 assert r->'data'->>'chat_start_after_seq'='7','reconnect exposed offline interval';
 r:=public.reconnect_room(room_,bm,1,ctx,req);
 assert r->>'outcome'='already_applied' and r->'data'->>'generation'='2','reconnect retry changed window';
 r:=public.heartbeat(room_,bm,1,2);
 assert r->>'code'='STALE_CONNECTION','old generation renewed';
 reset role;
 assert (select count(*)=1 from private.chat_windows where membership_id=bm and end_at_seq is null),'multiple open windows';
 -- Última saída de admin com reserva: manter sala sem admin e recuperar no retorno.
 update private.connections set last_seen_at=statement_timestamp()-interval '30 seconds',suspect_at=statement_timestamp()-interval '5 seconds',
  grace_deadline=statement_timestamp()+interval '55 seconds' where membership_id=bm;
 select revision into rev_before from private.rooms where id=room_;
 perform set_config('request.jwt.claim.sub',a::text,true);
 set local role authenticated;
 ctx:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.leave_room(room_,membership_,1,null,null,ctx,gen_random_uuid());
 assert r->>'code' is null,'admin leave failed';
 reset role;
 assert (select revision=rev_before+1 from private.rooms where id=room_),'multiple room revisions in one command';
 assert (select status='active' and admin_state='awaiting_successor' and admin_membership_id is null from private.rooms where id=room_),'reserved participant lost room';
 perform set_config('request.jwt.claim.sub',b::text,true);
 set local role authenticated;
 ctx:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.reconnect_room(room_,bm,2,ctx,gen_random_uuid());
 assert r->'data'->>'generation'='3','reserved return failed';
 r:=public.get_room_snapshot(room_,bm,3);
 assert r->'data'->>'admin_membership_id'=bm::text,'successor not assigned';
 r:=public.leave_room(room_,bm,3,null,null,ctx,gen_random_uuid());
 assert r->>'code' is null,'last leave failed';
 reset role;
 assert (select status='closed' and admin_state='none' from private.rooms where id=room_),'last leave did not close';
 assert (select invalidated_at is not null from private.room_codes where room_id=room_),'closed code usable';
 assert (select media_id is null and status='empty' from private.playback where room_id=room_),'closed playback not empty';
end
$test$;
rollback;
select 'rooms_lifecycle: passed; fixtures rolled back' as result;
