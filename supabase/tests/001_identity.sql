-- Executar em banco de desenvolvimento após migrações. Fixture inteiramente revertida.
begin;
do $test$
declare
  a uuid := gen_random_uuid(); b uuid := gen_random_uuid();
  ctx uuid; req uuid := gen_random_uuid(); r jsonb; first_code text;
  rejected boolean;
begin
  assert to_regprocedure('public.ensure_profile(text)') is not null, 'bootstrap RPC missing';
  insert into auth.users(id, aud, role, is_anonymous) values
    (a, 'authenticated', 'authenticated', true), (b, 'authenticated', 'authenticated', true);
  insert into private.beta_testers(user_id) values (a),(b);
  perform set_config('request.jwt.claim.sub',a::text,true);
  set local role authenticated;
  r := public.ensure_profile('Ana');
  assert r->'data'->>'nickname' = 'Ana', 'bootstrap nickname';
  first_code := r->'data'->>'public_code';
  assert length(first_code)=12, 'personal code';
  assert (r->'data'->'preferences'->>'notify_invites')::boolean, 'invite default';
  assert (r->'data'->'preferences'->>'notify_friendships')::boolean, 'friendship default';
  r := public.ensure_profile('Outro');
  assert r->'data'->>'nickname' = 'Ana', 'bootstrap retry changed nickname';
  assert r->'data'->>'public_code' = first_code, 'bootstrap retry changed code';
  r := public.ensure_profile('X');
  assert r->>'code'='INVALID_INPUT', 'short nickname accepted';
  r := public.get_command_context();
  ctx := (r->'data'->>'command_context_id')::uuid;
  r := public.change_nickname('Bia',0,ctx,req);
  assert r->'data'->>'nickname' = 'Bia', 'nickname not updated';
  assert r->'revisions'->>'profile_revision'='1', 'revision transport must be decimal string';
  r := public.change_nickname('Bia',0,ctx,req);
  assert r->>'outcome'='already_applied', 'retry reapplied';
  r := public.change_nickname('Diferente',0,ctx,req);
  assert r->>'code'='IDEMPOTENCY_MISMATCH', 'request id allowed different payload';
  r := public.change_nickname('Outra',0,ctx,gen_random_uuid());
  assert r->>'code'='CONFLICT', 'stale revision overwrote data';
  r := public.set_notification_preference('invites',false,0,ctx,gen_random_uuid());
  assert not (r->'data'->>'notify_invites')::boolean, 'preference not saved';
  assert (r->'data'->>'notify_friendships')::boolean, 'unrelated preference overwritten';
  r := public.save_message_preferences('top','medium','slow',1,ctx,gen_random_uuid());
  assert r->'data'->>'overlay_position'='top', 'overlay not saved';
  assert not (r->'data'->>'notify_invites')::boolean, 'overlay overwrote notification';
  r := public.set_notification_preference('unknown',true,2,ctx,gen_random_uuid());
  assert r->>'code'='INVALID_INPUT', 'invalid kind accepted';
  rejected := false;
  begin perform * from private.profiles; exception when insufficient_privilege then rejected := true; end;
  assert rejected, 'direct table read allowed';
  rejected := false;
  begin update private.profiles set nickname='Hacked'; exception when insufficient_privilege then rejected := true; end;
  assert rejected, 'direct table write allowed';
  perform set_config('request.jwt.claim.sub',b::text,true);
  r := public.ensure_profile('Carol');
  assert r->'data'->>'nickname'='Carol', 'second identity wrong';
  r := public.change_nickname('Roubo',0,ctx,gen_random_uuid());
  assert r->>'code'='REQUEST_EXPIRED', 'another actor context accepted';
  r := public.get_my_profile();
  assert r->'data'->>'nickname'='Carol', 'profile leaked across identities';
  reset role;
  update private.command_contexts set expires_at=clock_timestamp()-interval '1 second', issued_at=clock_timestamp()-interval '1 hour' where id=ctx;
  perform set_config('request.jwt.claim.sub',a::text,true);
  set local role authenticated;
  r := public.change_nickname('Bia',0,ctx,req);
  assert r->>'outcome'='already_applied', 'expired committed request not recognized';
  r := public.change_nickname('Velho',1,ctx,gen_random_uuid());
  assert r->>'code'='REQUEST_EXPIRED', 'expired context allowed new command';
  reset role;
  update private.beta_testers set enabled=false where user_id=a;
  set local role authenticated;
  r := public.get_my_profile();
  assert r->>'code'='FORBIDDEN', 'revoked beta still reads';
  reset role;
  perform set_config('request.jwt.claim.sub','',true);
  set local role anon;
  rejected := false;
  begin perform public.get_my_profile(); exception when insufficient_privilege then rejected := true; end;
  assert rejected, 'anon RPC access allowed';
  reset role;
end
$test$;
rollback;
select 'identity_preferences: passed; fixtures rolled back' as result;
