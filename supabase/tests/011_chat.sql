begin;
do $test$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); ac uuid; bc uuid; room_ uuid; am uuid; bm uuid;
 aw uuid; bw uuid; req uuid:=gen_random_uuid(); mid uuid:=gen_random_uuid(); r jsonb; seq_ text;
begin
 assert to_regprocedure('public.send_message(uuid,uuid,bigint,uuid,text,uuid,uuid,uuid)') is not null,'chat API missing';
 insert into auth.users(id) values(a),(b);
 insert into private.beta_testers(user_id) values(a),(b);
 perform set_config('request.jwt.claim.sub',a::text,true); set local role authenticated;
 perform public.ensure_profile('Ana'); ac:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.create_room('Chat',true,ac,gen_random_uuid()); room_:=(r->'data'->>'room_id')::uuid; am:=(r->'data'->>'membership_id')::uuid; aw:=(r->'data'->>'chat_window_id')::uuid;
 r:=public.send_message(room_,am,1,aw,'Antes da entrada',gen_random_uuid(),ac,gen_random_uuid());
 assert r->'data'->>'seq'='1','server message sequence';
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.ensure_profile('Bia'); bc:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.join_room(jsonb_build_object('public_room_id',room_),bc,gen_random_uuid()); bm:=(r->'data'->>'membership_id')::uuid; bw:=(r->'data'->>'chat_window_id')::uuid;
 r:=public.list_messages(room_,bm,1,bw,0,null,100);
 assert jsonb_array_length(r->'data'->'messages')=0,'new entrant read history';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.send_message(room_,am,1,aw,'Mensagem atual',mid,ac,req);
 assert r->'data'->>'seq'='2','second message sequence';
 r:=public.send_message(room_,am,1,aw,'Mensagem atual',mid,ac,req);
 assert r->>'outcome'='already_applied','message retry duplicated';
 assert not(r->'data' ? 'body'),'receipt leaked message body';
 r:=public.send_message(room_,am,1,aw,'Alterada',mid,ac,gen_random_uuid());
 assert r->>'code'='IDEMPOTENCY_MISMATCH','client id reused for different body';
 r:=public.change_nickname('Ana Nova',0,ac,gen_random_uuid());
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.list_messages(room_,bm,1,bw,0,null,100);
 assert jsonb_array_length(r->'data'->'messages')=1,'window sequence boundary failed';
 assert r->'data'->'messages'->0->>'sender_nickname'='Ana','old nickname overwritten';
 reset role;
 update private.connections set last_seen_at=statement_timestamp()-interval '30 seconds',suspect_at=statement_timestamp()-interval '5 seconds',
 grace_deadline=statement_timestamp()+interval '55 seconds' where membership_id=bm;
 set local role authenticated;
 r:=public.list_messages(room_,bm,1,bw,0,null,100);
 assert r->>'code'='RECONNECT_REQUIRED','grace could read chat';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.send_message(room_,am,1,aw,'Durante a queda',gen_random_uuid(),ac,gen_random_uuid());
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.reconnect_room(room_,bm,1,bc,gen_random_uuid());
 bw:=(r->'data'->>'chat_window_id')::uuid;
 r:=public.list_messages(room_,bm,2,bw,0,null,100);
 assert jsonb_array_length(r->'data'->'messages')=0,'reconnect recovered disconnected interval';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.send_message(room_,am,1,aw,'Depois do retorno',gen_random_uuid(),ac,gen_random_uuid());
 perform set_config('request.jwt.claim.sub',b::text,true);
 r:=public.list_messages(room_,bm,2,bw,0,null,100);
 assert jsonb_array_length(r->'data'->'messages')=1 and r->'data'->'messages'->0->>'body'='Depois do retorno','new window did not receive new message';
 assert r->'data'->'messages'->0->>'sender_nickname'='Ana Nova','new message did not snapshot current nickname';
 r:=public.list_messages(room_,bm,1,bw,0,null,100);
 assert r->>'code'='STALE_CONNECTION','old generation read new chat';
 r:=public.list_messages(room_,bm,2,bw,0,99,100);
 assert r->>'code'='INVALID_INPUT','both cursors accepted';
 reset role;
 assert (select count(*)=4 from private.messages where room_id=room_),'message deduplication failed';
end
$test$;
rollback;
select 'chat_windows_identity: passed; fixtures rolled back' as result;
