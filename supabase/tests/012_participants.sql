begin;
do $test$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); c uuid:=gen_random_uuid(); ac uuid; bc uuid; cc uuid; room_ uuid; am uuid; bm uuid; cm uuid; rev_ bigint; r jsonb;
begin
 assert to_regprocedure('public.transfer_admin(uuid,uuid,bigint,uuid,bigint,uuid,uuid)') is not null,'participant management API missing';
 insert into auth.users(id) values(a),(b),(c); insert into private.beta_testers(user_id) values(a),(b),(c);
 perform set_config('request.jwt.claim.sub',a::text,true); set local role authenticated;
 perform public.ensure_profile('Ana'); ac:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.create_room('Admin',true,ac,gen_random_uuid()); room_:=(r->'data'->>'room_id')::uuid; am:=(r->'data'->>'membership_id')::uuid;
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.ensure_profile('Bia'); bc:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.join_room(jsonb_build_object('public_room_id',room_),bc,gen_random_uuid()); bm:=(r->'data'->>'membership_id')::uuid;
 perform set_config('request.jwt.claim.sub',c::text,true);
 perform public.ensure_profile('Carol'); cc:=(public.get_command_context()->'data'->>'command_context_id')::uuid;
 r:=public.join_room(jsonb_build_object('public_room_id',room_),cc,gen_random_uuid()); cm:=(r->'data'->>'membership_id')::uuid;
 r:=public.get_room_snapshot(room_,cm,1); rev_:=(r->'revisions'->>'room_revision')::bigint;
 r:=public.set_control_permission(room_,cm,1,bm,true,rev_,cc,gen_random_uuid());
 assert r->>'code'='FORBIDDEN','ordinary member granted control';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.set_control_permission(room_,am,1,bm,true,rev_,ac,gen_random_uuid());
 assert r->>'code' is null,'admin control grant failed';
 rev_:=(r->'revisions'->>'room_revision')::bigint;
 r:=public.transfer_admin(room_,am,1,bm,rev_,ac,gen_random_uuid());
 assert r->'data'->>'admin_membership_id'=bm::text,'admin transfer failed';
 reset role;
 assert (select state='active' and not can_control from private.memberships where id=am),'former admin got implicit control';
 assert (select can_control from private.memberships where id=bm),'prior individual permission lost';
 perform set_config('request.jwt.claim.sub',b::text,true); set local role authenticated;
 r:=public.get_room_snapshot(room_,bm,1); rev_:=(r->'revisions'->>'room_revision')::bigint;
 r:=public.transfer_admin(room_,bm,1,am,rev_,bc,gen_random_uuid());
 assert r->>'code' is null,'transfer back failed';
 reset role;
 assert (select can_control from private.memberships where id=bm),'former admin lost previous individual permission';
 perform set_config('request.jwt.claim.sub',a::text,true); set local role authenticated;
 r:=public.get_room_snapshot(room_,am,1); rev_:=(r->'revisions'->>'room_revision')::bigint;
 r:=public.kick_member(room_,am,1,cm,rev_,ac,gen_random_uuid());
 assert r->>'code' is null,'kick failed';
 perform set_config('request.jwt.claim.sub',c::text,true);
 r:=public.join_room(jsonb_build_object('public_room_id',room_),cc,gen_random_uuid());
 assert r->>'code'='FORBIDDEN','kicked identity rejoined';
 r:=public.get_room_snapshot(room_,cm,1);
 assert r->>'code'='REJOIN_REQUIRED','kicked membership read snapshot';
 reset role;
 assert exists(select 1 from private.room_bans where room_id=room_ and user_id=c),'ban not recorded';
 assert (select state='ended' and end_reason='kicked' from private.memberships where id=cm),'kick not terminal';
end
$test$;
rollback;
select 'participant_management: passed; fixtures rolled back' as result;
